<?php

declare(strict_types=1);

namespace ModxInstaller;

use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Process\Process;

final class Docker
{
    public function check(): array
    {
        $results = [];
        foreach (['Docker daemon' => ['docker', 'info', '--format', '{{.ServerVersion}}'], 'Docker Compose' => ['docker', 'compose', 'version', '--short']] as $label => $command) {
            try {
                $process = new Process($command);
                $process->setTimeout(15);
                $process->run();
                $ok = $process->isSuccessful();
                $detail = trim($process->getOutput());
                if ($label === 'Docker Compose' && $ok && version_compare(ltrim($detail, 'v'), '2.20.0', '<')) {
                    $ok = false;
                    $detail = 'Compose >=2.20 is required.';
                }
                $results[$label] = ['ok' => $ok, 'detail' => $ok ? $detail : ($detail ?: 'Unavailable. Install/start Docker with Compose >=2.20.')];
            } catch (\Throwable $e) {
                $results[$label] = ['ok' => false, 'detail' => $e->getMessage()];
            }
        }
        return $results;
    }

    public function requireAvailable(): void
    {
        foreach ($this->check() as $label => $result) {
            if (!$result['ok']) {
                throw new \RuntimeException($label.': '.$result['detail']);
            }
        }
    }

    public function compose(Project $project, array $arguments, OutputInterface $output, ?string $stdin = null, ?float $timeout = 900): void
    {
        $env = $project->env();
        $command = ['docker', 'compose', '--project-directory', $project->directory, '--env-file', $project->directory.'/.env', '-f', $project->directory.'/compose.yaml', '--project-name', $project->metadata['name'], ...$arguments];
        $process = new Process($command, $project->directory, $env, $stdin, $timeout);
        // Stream long builds/followed logs without retaining an unbounded copy.
        $process->disableOutput();
        $process->run(static function (string $type, string $buffer) use ($output): void {
            $output->write($buffer, false, OutputInterface::OUTPUT_RAW);
        });
        if (!$process->isSuccessful()) {
            throw new \RuntimeException('Docker Compose failed (exit '.$process->getExitCode().'). Project files and database have been preserved. Inspect modx logs; rerun modx up after fixing the cause.');
        }
    }

    public function up(Project $project, OutputInterface $output): bool
    {
        $lock = new ProjectLock($project->directory);
        $installed = !is_file($project->directory.'/.modx-installed');
        $env = $project->env($installed);
        if (!$installed && !is_file($project->directory.'/app/core/config/config.inc.php')) {
            throw new \RuntimeException('Installed project configuration is missing. Restore it from backup; automatic reinstallation is disabled.');
        }
        if ((int)$env['LOCAL_UID'] === 0) {
            throw new \RuntimeException('PHP-FPM requires a non-root project owner. Create the site as a regular host user, or correct LOCAL_UID/LOCAL_GID and project ownership before startup.');
        }
        $this->requireAvailable();
        $this->compose($project, ['up', '-d', '--build', '--wait', '--wait-timeout', '180', 'db', 'php'], $output);
        if ($installed) {
            $payload = json_encode(array_intersect_key($env, array_flip(['DB_NAME', 'DB_USER', 'DB_PASSWORD', 'ADMIN_USER', 'ADMIN_PASSWORD', 'ADMIN_EMAIL', 'HTTP_PORT', 'MODX_LANGUAGE'])), JSON_THROW_ON_ERROR);
            if (!is_file($project->directory.'/app/core/config/config.inc.php')) {
                $this->runtime($project, 'install', [], $output, $payload);
            }
            $this->runtime($project, 'verify', [], $output, $payload);
            (new \Symfony\Component\Filesystem\Filesystem())->dumpFile($project->directory.'/.modx-installed', "Installation and administrator verified.\n");
        } else {
            // A marker does not prove that the database volume still exists.
            // Do not depend on the initial password, which the user may have changed.
            $this->runtime($project, 'verify', ['--installed'], $output, '{}');
        }
        $this->compose($project, ['up', '-d', '--wait', '--wait-timeout', '60', 'web'], $output);
        $this->runtime($project, 'verify', ['--http'], $output, '{}');
        return $installed;
    }

    private function runtime(Project $project, string $script, array $arguments, OutputInterface $output, string $payload): void
    {
        // Use the CLI's patched runtime, including for projects generated by older
        // releases. Only code is in argv; credentials remain on stdin.
        $code = substr(file_get_contents(dirname(__DIR__).'/resources/'.$script.'.php'), 5);
        $this->compose($project, ['exec', '-T', 'php', 'php', '-r', $code, '--', ...$arguments], $output, $payload, $script === 'install' ? 900 : 180);
    }
}
